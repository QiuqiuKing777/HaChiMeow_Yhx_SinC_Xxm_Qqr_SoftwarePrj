def _rule_based_reply(message: str) -> str:
    """简单关键词匹配，返回本地回复；未命中返回 None。"""
    msg_lower = message.lower()
    for keywords, reply in _RULES:
        for kw in keywords:
            if kw.lower() in msg_lower:
                return reply
    return None


def _openai_reply(message: str, history: list) -> str:
    """调用 OpenAI ChatCompletion，需要环境变量 OPENAI_API_KEY。"""
    import json
    import urllib.request

    api_key = os.environ.get('OPENAI_API_KEY', '')
    api_base = os.environ.get('OPENAI_API_BASE', 'https://api.openai.com')
    model = os.environ.get('OPENAI_MODEL', 'gpt-3.5-turbo')

    system_prompt = (
        '你是"宠爱有家"宠物领养与社区服务平台的 AI 宠物助手。'
        '你的职责是回答用户关于宠物领养、日常养护、宠物健康、平台功能使用等问题。'
        '请用简洁、友好的中文回复，必要时分条说明。'
        '不要回答与宠物和平台无关的问题。'
    )

    messages = [{'role': 'system', 'content': system_prompt}]
    for h in (history or []):
        if h.get('role') in ('user', 'assistant'):
            messages.append({'role': h['role'], 'content': h['content']})
    messages.append({'role': 'user', 'content': message})

    payload = json.dumps({
        'model': model,
        'messages': messages,
        'max_tokens': 800,
        'temperature': 0.7,
    }).encode('utf-8')

    req = urllib.request.Request(
        f'{api_base.rstrip("/")}/v1/chat/completions',
        data=payload,
        headers={
            'Content-Type': 'application/json',
            'Authorization': f'Bearer {api_key}',
        },
        method='POST',
    )
    with urllib.request.urlopen(req, timeout=20) as resp:
        data = json.loads(resp.read().decode('utf-8'))
    return data['choices'][0]['message']['content'].strip()


